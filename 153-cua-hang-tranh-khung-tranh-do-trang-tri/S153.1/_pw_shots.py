import os
from playwright.sync_api import sync_playwright

url = 'file:///' + os.path.abspath('index.html').replace(os.sep, '/')
out = os.path.abspath('_shots')
os.makedirs(out, exist_ok=True)
with sync_playwright() as p:
    b = p.chromium.launch()
    # desktop
    pg = b.new_page(viewport={'width': 1280, 'height': 900})
    pg.route('**://fonts.googleapis.com/**', lambda r: r.abort())
    pg.route('**://fonts.gstatic.com/**', lambda r: r.abort())
    pg.goto(url, wait_until='domcontentloaded')
    pg.wait_for_timeout(1200)
    pg.screenshot(path=os.path.join(out, 'd_hero.png'))
    pg.evaluate("document.getElementById('dong-khung').scrollIntoView()")
    pg.wait_for_timeout(900)
    pg.screenshot(path=os.path.join(out, 'd_cfg.png'))
    pg.evaluate("document.getElementById('set-3-tranh').scrollIntoView()")
    pg.wait_for_timeout(900)
    pg.screenshot(path=os.path.join(out, 'd_set.png'))
    pg.evaluate("document.getElementById('hot').scrollIntoView()")
    pg.wait_for_timeout(900)
    pg.screenshot(path=os.path.join(out, 'd_khoi8.png'))
    pg.close()
    # mobile
    m = b.new_page(viewport={'width': 390, 'height': 844})
    m.route('**://fonts.googleapis.com/**', lambda r: r.abort())
    m.route('**://fonts.gstatic.com/**', lambda r: r.abort())
    m.goto(url, wait_until='domcontentloaded')
    m.wait_for_timeout(1000)
    m.screenshot(path=os.path.join(out, 'm_hero.png'))
    m.evaluate("document.getElementById('hot').scrollIntoView()")
    m.wait_for_timeout(900)
    m.screenshot(path=os.path.join(out, 'm_khoi8.png'))
    m.evaluate("document.getElementById('dong-khung').scrollIntoView()")
    m.wait_for_timeout(900)
    m.screenshot(path=os.path.join(out, 'm_cfg.png'))
    m.close()
    b.close()
print('done')
